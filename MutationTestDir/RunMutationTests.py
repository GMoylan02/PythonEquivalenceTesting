import signal
import sys
import os
import subprocess
import importlib
import pkgutil
import time

from src.ProgramEquivalence import get_module_functions

TIMEOUT_SECONDS = 20
BATCH_SIZE = 2
TEMP_FILENAME = "../src/temp_fuzz_node.py"
UTILS_IMPORT_PATH = "src.UniversalStrategy"
TARGET_PACKAGE = "mutmut_test"
PROJECT_ROOT = os.path.abspath(os.getcwd())

"""
Create new python files dynamically, each with {BATCH_SIZE} tests and run hypofuzz on them. 
This is necessary because hypofuzz does not work well if I simply created 1 python file and stuck every test into it,
and this way I can dynamically test every mutant generated by mutmut. 

Also manually send a kill signal to every process after each time we run hypofuzz, otherwise the processes appear
to continue getting stalled and I almost overheated my CPU earlier because of this.
"""


def run_fuzzing_session():
    os.environ["MUTANT_UNDER_TEST"] = ""
    with open("hypofuzz_failures.log", 'w') as f:
        f.write("")

    sys.path.insert(0, PROJECT_ROOT)

    print(f"Loading modules from {TARGET_PACKAGE}...")
    try:
        base_pkg = importlib.import_module(TARGET_PACKAGE)
    except ImportError:
        print(f"Error: Could not import {TARGET_PACKAGE}. Check your path.")
        return

    modules = [
        importlib.import_module(f"{base_pkg.__name__}.{name}")
        for _, name, _ in pkgutil.iter_modules(base_pkg.__path__)
    ]

    total_mutants_found = 0
    test_batch = []

    for module in modules:
        print(f"\n--- Scanning Module: {module.__name__} ---")
        funcs = get_module_functions(module)

        originals = {
            name: func
            for name, func in funcs.items()
            if "__mutmut_orig" in name
        }

        for orig_name, orig_func in originals.items():
            for func_name, func_obj in funcs.items():
                if orig_name.replace("__mutmut_orig", "") in func_name and "__mutmut_orig" not in func_name:

                    test_batch.append((module, orig_func, func_obj))
                    total_mutants_found += 1

                    if len(test_batch) >= BATCH_SIZE:
                        run_batch_fuzz_case(test_batch)
                        test_batch = []

    if test_batch:
        run_batch_fuzz_case(test_batch)

    if os.path.exists("hypofuzz_failures.log"):
        with open("hypofuzz_failures.log", 'r') as f:
            mutants_identified = len(f.readlines())
    else:
        mutants_identified = 0

    print(f"\nMutants identified: {mutants_identified}/{total_mutants_found}")

    clean_directory()


def run_batch_fuzz_case(batch):
    """
    Generates a script for a list of (module, orig, mutant) tuples
    and runs hypofuzz on them simultaneously.
    """

    imports_block = f"""
import sys
import os

# Prevent crash on import for libraries like requests
os.environ["MUTANT_UNDER_TEST"] = ""

sys.path.insert(0, r'{PROJECT_ROOT}')
from {UTILS_IMPORT_PATH} import make_function_equivalence_test
"""
    tests_block = ""

    log_file = "hypofuzz_failures.log"
    initial_failure_count = 0
    if os.path.exists(log_file):
        with open(log_file, 'r') as f:
            initial_failure_count = len(f.readlines())

    print(f"Running batch of {len(batch)} tests...", end=" ", flush=True)

    for i, (module, orig_func, mutant_func) in enumerate(batch):
        mod_name = module.__name__

        mod_alias = f"mod_{i}"

        orig_name = orig_func.__name__
        mut_name = mutant_func.__name__
        test_func_name = f"test_{orig_name}_vs_{mut_name}_{i}"

        tests_block += f"""
import {mod_name} as {mod_alias}
orig_func_{i} = getattr({mod_alias}, "{orig_name}__mutmut_orig")
mutant_func_{i} = getattr({mod_alias}, "{mut_name}")
# Ensure log_failure=True so it writes to the file we are watching!
{test_func_name} = make_function_equivalence_test(orig_func_{i}, mutant_func_{i}, log_failure=True)
"""

    full_content = imports_block + "\n" + tests_block

    with open(TEMP_FILENAME, "w") as f:
        f.write(full_content)

    cmd = ["hypothesis", "fuzz", TEMP_FILENAME, "--no-dashboard"]

    env = os.environ.copy()
    env["PYTHONPATH"] = PROJECT_ROOT + os.pathsep + env.get("PYTHONPATH", "")

    process = None

    try:
        process = subprocess.Popen(
            cmd,
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            preexec_fn=os.setsid if os.name != 'nt' else None
        )

        start_time = time.time()

        while True:
            if process.poll() is not None:
                print("Finished (Process Exited)")
                break

            if time.time() - start_time > TIMEOUT_SECONDS:
                print("Timeout (Done)")
                break

            # we check to see if the log increased by {batch_size} lines,
            # indicating every test failed so we can exit early
            current_failure_count = 0
            if os.path.exists(log_file):
                with open(log_file, 'rb') as f:
                    current_failure_count = sum(1 for _ in f)

            new_failures = current_failure_count - initial_failure_count
            if new_failures >= len(batch):
                print(f"Early Exit! ({new_failures} failures found)")
                break

            time.sleep(0.5)

    except Exception as e:
        print(f"Error: {e}")

    kill_process_tree(process)

    # prevent race condition
    time.sleep(0.1)


def clean_directory():
    """Removes temporary files."""
    KEEP_FILES = {
        "hypofuzz_failures.log",
        "RunMutationTests.py",
        "__init__.py"
    }
    dir_path = os.path.dirname(os.path.abspath(__file__))

    for filename in os.listdir(dir_path):
        file_path = os.path.join(dir_path, filename)

        if filename in KEEP_FILES or not os.path.isfile(file_path):
            continue

        os.remove(file_path)


def kill_process_tree(process):
    if process is None:
        return

    if process.poll() is not None:
        return

    try:
        if os.name != 'nt':
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
        else:
            subprocess.call(
                ['taskkill', '/F', '/T', '/PID', str(process.pid)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
    except Exception:
        pass


if __name__ == "__main__":
    before = time.time()
    run_fuzzing_session()
    after = time.time()
    print(f"\nCompleted in {after - before} seconds.")